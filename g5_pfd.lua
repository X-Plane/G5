-- The AFCS status bar is up (and everything above the bottom row moved down,
-- see ARC_STEP) once the flight director is on; the AP field only fills when
-- the autopilot is engaged (Pilot's Guide 3.2.6). With a GFC 500 the status
-- box stays as an empty bar when AP and FD are off (figure 3-25, AFMS 7-1);
-- with another autopilot it shows while the flight director is on. No FD
-- modes without a valid attitude (3.3.3.2). Returns: bar up, FD modes shown.
-- Also asked by P.update (the transition runs there), with the gfc flag of
-- the last draw.
function P.bar_wanted(D, st, gfc)
    local fd_on = D.ap_mode > 0 and st.valid.att
    -- mode changes are tracked in P.update (sim time, every frame on the PFD
    -- page), so a disconnect that also turns the flight director off still
    -- gets its AP alert: the bar stays up for it
    local alert = (st.clock or 0) < math.max(fl.disc_until, fl.yd_until)
    -- the yaw damper alone also brings the bar up, showing only "YD" (real
    -- unit: FD and AP off, YD on)
    local yd_alone = D.yd_on ~= 0
    -- the provider's preflight test (ap_pft 1 running, 2 failed) needs the AP
    -- field even with the flight director off and an analog autopilot
    local pft = P.Esp and P.Esp.pic.pft
    local pft_up = pft == 1 or pft == 2
    local disp = cfg.show_ap_bar ~= 0 and (fd_on or alert or yd_alone or pft_up or (gfc and cfg.ap_bar_reserved ~= 0))
    return disp, fd_on
end

-- "HDG SYNC" while Heading Bug Auto Sync Mode runs (Pilot's Guide Rev M 3.3.5.2.1,
-- figure 3-19): a dark box above and to the left of the attitude indicator, right
-- of the TAS box and just under the heading tape ("HDG" white, "SYNC" cyan, the
-- bug's colour). Measured on the figure: 65 x 12 px, x 70..135, 6 px below the
-- tape's lower edge (`low`, P.draw)
local function hdg_sync_tag(low)
    local top = low - 6
    G.rect(70, top - 12, 135, top, G.black_alpha(0.85))
    G.box(70.5, top - 11.5, 134.5, top - 0.5, G.white_alpha(0.3), 1)
    local fs = G.rfont("bold", 8)
    G.rstr_c(fs, "HDG", 83, top - 10, C.white)
    G.rstr_c(fs, "SYNC", 118, top - 10, C.cyan)
end

function P.draw(D, st, gfc)
    local modes = P.afcs_modes(D, st)
    local disp, fd_on = P.bar_wanted(D, st, gfc)
    bar_gfc = gfc
    bar_target = disp and 1 or 0
    if bar_snap then bar_v, bar_snap = bar_target, false end
    -- levels (see ARC_STEP): bar and heading tape, each 0..1
    local bar_e = bar_v * bar_v * (3 - 2 * bar_v)
    local hdg_e = 1 - (1 - hdg_vis) * (1 - hdg_vis)   -- as heading_tape slides it
    local sb = math.floor(BAR_H * bar_e + 0.5)          -- bar / top row offset
    -- bottom of the lowest element (240 with neither); the art has it at 216
    local hdg_h = math.max(0, HDG_H - HDG_SLIDE * (1 - hdg_e))
    local low = math.floor(240 - sb - hdg_h + 0.5)
    -- bar alone (ALIGNING with a GFC 500): the full-size arc (R 91.4, as
    -- with nothing up), centre only ~3 px above the bar + heading tape
    -- layout, so its zero mark stands clear of the bar (real-unit
    -- video, same rectification). The other
    -- three layouts are unchanged: k = -7 / 0 / +7, yoff = low - 216 + k.
    local k = math.floor(ARC_STEP * (hdg_e + bar_e * hdg_e) + 0.5) - ARC_STEP
    local alone = math.floor(ARC_STEP * bar_e * (1 - hdg_e) + 0.5)
    yoff, arc_k = low - 216 + k - alone, k

    -- the red "AFCS" flag (autopilot / flight director failed, rel_otto; drawn
    -- in the AP field whenever the bar is up): Pilot's Guide, the flight
    -- director is not available then, so neither its cue nor its modes show.
    -- Only while the flag is drawn: with no bar (show_ap_bar = 0) nothing
    -- changes.
    local afcs_flag = D.otto_failed and sb > 0
    if afcs_flag then fd_on = false end

    -- attitude, tapes and readouts by yoff; the top row with the bar
    local air = st.valid.air
    G.push()
    G.translate(0, yoff)
    attitude(D, st, not afcs_flag)
    if air then vsi(D, st) end
    G.pop()
    G.push()
    G.translate(0, -sb)
    heading_tape(D, st)
    G.pop()
    G.push()
    G.translate(0, yoff)
    if air then
        speed_tape(D, st, gfc)
        altitude_tape(D, st)
        readouts(D, st)
    else
        air_fail()
    end
    vdi(D, st)
    if st.valid.att then trim_alert(D, st) end
    G.pop()
    G.push()
    G.translate(0, -sb)
    boxes_top(D, st, gfc)
    G.pop()
    yoff, arc_k = 0, 0

    -- rate of turn and slip come from the AHRS (AFMS: not available with
    -- an attitude failure)
    if st.valid.att then slip_turn(D) end
    cdi_pfd(D)
    boxes_bottom(D, st)
    if st.hdg_sync and st.valid.att then hdg_sync_tag(low) end
    -- "ESP / OFF" (real-unit video): ESP switched off while the
    -- autopilot is off (with the AP on ESP is not available anyway); stacked,
    -- between the CDI and the baro / VS boxes (drawn after them)
    local E = P.Esp
    if E ~= nil and E.usable() and not E.enabled and D.servos_on == 0 and P.esp_att_ok(st) then
        local fs = G.rfont("bold", 7)
        -- dark drop shadow (real unit): black copy 1 px down-right, then a
        -- softer one 1 px further
        local sh1, sh2 = G.black_alpha(0.85), G.black_alpha(0.4)
        for _, o in ipairs({ { 2, -2, sh2 }, { 1, -1, sh1 } }) do
            G.rstr_c(fs, "ESP", 225 + o[1], 40 + o[2], o[3])
            G.rstr_c(fs, "OFF", 225 + o[1], 30 + o[2], o[3])
        end
        G.rstr_c(fs, "ESP", 225, 40, C.white)
        G.rstr_c(fs, "OFF", 225, 30, C.white)
    end
    if sb > 0 then
        -- slides in from above with the top row
        G.push()
        G.translate(0, BAR_H - sb)
        ap_bar(D, st, gfc, fd_on, modes)
        G.pop()
    end
end

return P

        G.poly(C.magenta, { 316, y, 312, y - 8, 315.5, y - 8, 319.5, y })
    end
    G.pic(dir .. "VS_Arrow", 316, 120.5 + U.clamp(D.vs, -range, range) * 107.5 / range)
end


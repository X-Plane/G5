-- Vertical deviation (Vert_GS_Box 13 x 113 at the old POS: a label cell on
-- top, centre line on the altitude pointer y 121.5, dots every ~18.75 px).
-- Localizer tuned without a glideslope: "NO GS" between the outer dots.
local VDI_X, VDI_Y, VDI_DOT = 226.5, 128, 18.75
local VDI_C = VDI_Y - 6.5

-- VNAV (Pilot's Guide 2.3.4, figures 2-27 / 2-28; p.26 / p.78 HSI figures):
-- the VNAV path on the VDI as a magenta "<" under a magenta "V" (the VNAV
-- source label), the PFD's VSI also gets the path's vertical speed (vsi).
-- Sign of X-Plane's fms_vtk_pilot: +1 takes a positive value as the
-- aircraft above the path (the chevron goes below the centre).
-- Assumed, not verified in the sim: if the chevron goes up above a VNAV
-- descent path, flip it to -1.
local VNAV_SIGN = 1

-- VNAV deviation in dots (+ = path above the aircraft, chevron up: the
-- opposite sign of hsi_vdef, whose + is the aircraft above the path, diamond
-- below centre), or nil when the data mean nothing. Our condition (the sim has
-- no "VNAV deviation valid"; Pilot's Guide 3.3.4.6: shown while VNAV data
-- come in, a descent leg captured):
--   * Navigation Data enabled, GPS source, GPS course data (not lost with
--     the GAD 29), and no glideslope / glidepath on the VDI (GS / GP use the
--     same box and have priority);
--   * a descent path: fms_vpa_pilot > 0;
--   * the autopilot's VNAV armed / active (vnav_status), or the top of
--     descent less than a minute ahead (0 < fms_distance_to_tod_pilot <=
--     GS / 60 nm). 0 is also what the sim reads with no TOD computed (seen
--     2026-10-29: tod 0, vpa 0, fpta -1000 for a plan with altitudes), so 0
--     alone never counts as "near" (review 2026-10-29);
--   * above the path's target altitude (fms_fpta_pilot, when given).
-- Full scale (the outer, 2nd dot) = the VNAV Deviation Scale (vnav_dev_scale,
-- Installation Manual 5.3.1 note 5): dots = 2 x deviation / scale.
-- NO GP (D.no_gp, g5_sim Sim.update_no_gp) has the VDI before VNAV (our rule).
function P.vnav(D, st)
    if cfg.nav_data == 0 or D.hsi_src ~= 2 or D.hsi_show_v ~= 0 or st.gps_nav_lost or D.no_gp then return nil end
    if (D.fms_vpa or 0) <= 0 then return nil end
    local tod = D.fms_tod or 0
    local near_tod = tod > 0 and tod <= math.max(0, D.gs) / 60
    if D.vnav_status == 0 and not near_tod then return nil end
    if (D.fms_fpta or 0) > 0 and D.alt <= D.fms_fpta then return nil end
    return -VNAV_SIGN * 2 * (D.fms_vtk or 0) / (cfg.vnav_dev_scale or 500)
end

-- the chevron: apex at x0 (the box's left inner edge), 10 x 20 px, 4 px
-- across each arm; pegged at 2.4 dots like the diamond and clipped by the
-- box interior y_lo..y_hi (PG p.26: only the upper arm left at the end)
function P.vnav_chevron(x0, cy, dot, dots, y_lo, y_hi)
    local y = cy + U.clamp(dots, -2.4, 2.4) * dot
    clip(x0, y_lo, x0 + 10, y_hi)
    G.poly(C.magenta, { x0, y, x0 + 4, y, x0 + 10, y + 10, x0 + 6, y + 10 })
    G.poly(C.magenta, { x0, y, x0 + 6, y - 10, x0 + 10, y - 10, x0 + 4, y })
    G.unclip()
end


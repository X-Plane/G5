-- Pitch ladder: one ArtHori_Ladder cell per 2.5 deg line (k = -36..36, line
-- pitch -2.5 k, cell centre 9 k - 1 px below the horizon on the bitmap). Like
-- the real unit, only lines near the current pitch show: full within
-- LADDER_FULL deg, fading to nothing over the next LADDER_FADE deg. The
-- horizon line (k = 0) always shows.
-- real-unit photo (pitch ~+4): the 20 deg line is already
-- fading while the 10 / 15 deg lines are full
local LADDER_FULL, LADDER_FADE = 12, 5
-- Expanded: a window about as tall in pixels, fitted to figure 2-5 (near 0
-- deg: 7.5 deg full, 10 deg fading; a 7 / 3 window would hide the 10);
-- its own sheet with the 5-deg labels (generated by an offline tool, not
-- included), lines 2.5 x PPD_EXP apart
local LADDER_FULL_EXP, LADDER_FADE_EXP = 8, 3

local function ladder(pitch)
    local full, fade, sheet, step = LADDER_FULL, LADDER_FADE, "ArtHori_Ladder", 2.5 * ppd()
    if expanded() then
        full, fade, sheet, step = LADDER_FULL_EXP, LADDER_FADE_EXP, "ArtHori_Ladder_Exp", 2.5 * PPD_EXP
    end
    local y0 = CY - pitch * ppd()
    local k0 = math.max(-36, math.ceil(-(pitch + full + fade) / 2.5))
    local k1 = math.min(36, math.floor(-(pitch - full - fade) / 2.5))
    if k0 > 0 then k0 = 0 end
    if k1 < 0 then k1 = 0 end
    for k = k0, k1 do
        local a = 1
        if k ~= 0 then
            local d = math.abs(-2.5 * k - pitch)
            a = U.clamp((full + fade - d) / fade, 0, 1)
        end
        if a > 0 then
            G.pic_rot(sheet, CX, y0 - (step * k - 1), 90, G.white_alpha(a), k + 36)
        end
    end
end

-- Unusual-attitude chevrons (Red_Arrows, the ladder's rotated layout): on
-- the art (3.6 px / deg) the sky group starts 181 px above the horizon
-- (~50 deg nose up), the ground group 145 px below (~40 deg nose down).
-- Expanded keeps those pitches: each group (a Red_Arrows_Split cell) moves
-- out by the extra px of its start.
local RED_SKY_DEG, RED_GND_DEG, RED_ART_PPD = 181 / 3.6, 145 / 3.6, 3.6

local function red_arrows(pitch)
    local y = CY - pitch * ppd()
    local extra = ppd() - RED_ART_PPD
    if not expanded() and extra == 0 then
        G.pic_rot("Red_Arrows", CX, y, 90)
        return
    end
    G.pic_rot("Red_Arrows_Split", CX, y + RED_SKY_DEG * extra, 90, nil, 0)
    G.pic_rot("Red_Arrows_Split", CX, y - RED_GND_DEG * extra, 90, nil, 1)
end

-- Roll_Arc_Sheet = the arc and ticks of Roll_Indicator (rows 0..48), one cell
-- per pixel of radius change, 7 px larger .. 7 px smaller (cell arc_k + 7,
-- generated by an offline tool, not included); its centre on screen, and the lowest row of the
-- arc in Roll_Indicator, below which it only holds the aircraft symbol
local ROLL_ARC_CY, ROLL_ARC_BOTTOM = 188, 163
-- the arc line is a circle of radius ~84.4 around (159, 121)
local ARC_X, ARC_Y, ARC_R = 159, 121, 84.4

-- the arc at the current radius (ARC_R - arc_k, same centre)
local function roll_arc()
    G.pic("Roll_Arc_Sheet", 159, ROLL_ARC_CY, nil, arc_k + 7)
end

-- Standard-turn roll reference (Figure 2-1 #26, 3-4): green triangles just outside
-- the arc at the bank angle of a 3 deg/s turn at the current TAS, pointing in
-- at the arc like the zero mark. `rot` = rotation of the scale (ground pointer).
local STD_RATE = math.rad(3)
local function std_turn_ref(D, rot)
    -- needs a valid airspeed: with the readout dashed (on the ground, TAS
    -- "___") there are none, as on the real unit; X-Plane's TAS there is wind
    if cfg.std_turn_ref == 0 or D.tas < 30 or not spd_alive then return end
    local b = math.deg(math.atan(D.tas * 0.514444 * STD_RATE / 9.80665))
    local r = ARC_R - arc_k
    G.push()
    G.rotate(CX, CY, rot)
    for s = -1, 1, 2 do
        local a = s * b
        local tx, ty = G.polar(ARC_X, ARC_Y, r + 2, a)
        local lx, ly = G.polar(ARC_X, ARC_Y, r + 10, a - 3.4)
        local rx, ry = G.polar(ARC_X, ARC_Y, r + 10, a + 3.4)
        G.poly(C.green, { tx, ty, rx, ry, lx, ly })
    end
    G.pop()
end

-- ESP Roll Limit Indicators (Pilot's Guide 3.5.1, figures 3-25 .. 3-28):
-- green double marks across the arc at the configured bank limit while ESP is
-- armed; once roll protection engages they turn yellow and move 15 deg in, to
-- where ESP lets go. Marks: two 3 px lines 4 px apart with a dark edge, from
-- 5 px inside to 11 px outside the arc. `rot` as std_turn_ref.
-- Arming / disarming animates (real-unit video at 30 fps): 0.25 s after ESP arms (autopilot off) the marks slide up the arc
-- from 15 deg lower while fading in, 0.17 s; when it disarms (autopilot on)
-- they slide back down while fading out, 0.12 s.
local ESP_DELAY_S, ESP_IN_S, ESP_OUT_S, ESP_SLIDE_DEG = 0.25, 0.17, 0.12, 15
local esp_vis, esp_wait = 0, 0
-- pitch engagement chevrons (esp_pitch_chevrons): fade level and the way they
-- point (+1 up, -1 down) while shown. The pitch bit can flicker frame to
-- frame at the engagement limit (the sim showed 2 / 10 / 0): a fade that
-- restarts on every dropped frame never reaches full opacity and the chevrons
-- look pale. So the bit has to stay off for HOLD_S before the fade-out starts
-- (`off` counts that time); the fade-in is short.
local PITCH_FADE = { IN_S = 0.08, OUT_S = 0.2, HOLD_S = 0.35, off = 0 }
local pitch_vis, pitch_dir = 0, 1

-- ESP indications (roll marks, pitch chevrons, MAXSPD / MINSPD, "ESP OFF") need
-- this unit's own attitude valid and aligned: not during ALIGNING / KEEP WINGS
-- LEVEL / ATTITUDE FAIL (the ESP provider ignores this G5 then too, G5.lua
-- att_ok). Another display's heartbeat can still arm ESP.
function P.esp_att_ok(st)
    return st.valid.att and not st.aligning
end

local function esp_anim(dt, D, st)
    local E = P.Esp
    if E ~= nil and not P.esp_att_ok(st) then
        -- gone at once, no fade; they come in afresh when the attitude is valid
        esp_vis, esp_wait, pitch_vis, PITCH_FADE.off = 0, 0, 0, PITCH_FADE.HOLD_S
        return
    end
    if E ~= nil and E.usable() and E.armed then
        esp_wait = esp_wait + dt
        if esp_wait >= ESP_DELAY_S then esp_vis = U.approach(esp_vis, 1, 1 / ESP_IN_S, dt) end
    else
        esp_wait = 0
        esp_vis = U.approach(esp_vis, 0, 1 / ESP_OUT_S, dt)
    end
    local PF = PITCH_FADE
    local usable = E ~= nil and E.usable()
    if usable and E.pitch then
        PF.off = 0
        pitch_vis = U.approach(pitch_vis, 1, 1 / PF.IN_S, dt)
        -- the provider's push direction; without one, against the pitch
        pitch_dir = (E.pitch_dir ~= 0) and E.pitch_dir or ((D and D.pitch or 0) > 0 and -1 or 1)
    else
        PF.off = usable and (PF.off + dt) or PF.HOLD_S    -- no hold when ESP is gone
        if PF.off >= PF.HOLD_S then
            pitch_vis = U.approach(pitch_vis, 0, 1 / PF.OUT_S, dt)
        end
    end
end

-- colours with alpha, 20 steps, cached (XPLMMakeColor is a C call)
local esp_cols = {}
local function esp_col(hexstr, a)
    local k = hexstr .. math.floor(a * 20 + 0.5)
    local c = esp_cols[k]
    if c == nil then
        c = G.hex(hexstr, math.floor(a * 20 + 0.5) / 20)
        esp_cols[k] = c
    end
    return c
end

local function esp_marks(rot)
    local E = P.Esp
    if E == nil or not E.usable() or esp_vis <= 0 then return end
    local v = esp_vis
    local e = 1 - (1 - v) * (1 - v)          -- ease-out into place
    local a0 = (E.armed and E.roll) and (E.roll_limit - 15) or E.roll_limit
    a0 = a0 + (1 - e) * ESP_SLIDE_DEG
    local col = esp_col((E.armed and E.roll) and "E8D820" or "3BBF1A", v)
    local edge = esp_col("000000", v)
    local r = ARC_R - arc_k
    G.push()
    G.rotate(CX, CY, rot)
    -- dark edges of all four lines first, then the colour (kGGGkGGGk)
    for pass = 1, 2 do
        for s = -1, 1, 2 do
            local a = s * a0
            for k = -1, 1, 2 do
                -- 2 px either side of the radial
                local ox, oy = G.polar(0, 0, 2, a + 90 * k)
                local x0, y0 = G.polar(ARC_X + ox, ARC_Y + oy, r - 5, a)
                local x1, y1 = G.polar(ARC_X + ox, ARC_Y + oy, r + 11, a)
                if pass == 1 then
                    G.line(x0, y0, x1, y1, edge, 5)
                else
                    G.line(x0, y0, x1, y1, col, 3)
                end
            end
        end
    end
    G.pop()
end

-- ESP pitch engagement chevrons (Pilot's Guide Rev M 3.5.2, figure 3-30): two
-- bold yellow chevrons over the pitch ladder once ESP pushes the pitch,
-- pointing the way it pushes the nose (nose low: up, nose high: down). Fixed
-- to the screen like the aircraft symbol (the figure's horizon is tilted, the
-- chevrons are not). Measured on the figure (2 crop px = 1 screen px): each
-- chevron 50 wide and 33 tall, the two 36 apart; pointing up their tips are
-- 22 and -14 px from the attitude centre, pointing down 30.5 and -3 px (the
-- figure shows one frame of each; the real unit may move them).
local PCH_HALF_W, PCH_RISE, PCH_T = 25, 19, 14
local PCH_TIPS_UP, PCH_TIPS_DOWN = { 22, -14 }, { 30.5, -3 }

-- one chevron: `tip` is its point (the apex pointing up, the vertex down);
-- two arms, each a band PCH_T tall at the tip, running PCH_RISE away from it
local function chevron(cx, tip, up, half_w, rise, t, col)
    local s = up and -1 or 1
    G.poly(col, { cx, tip, cx - half_w, tip + s * rise, cx - half_w, tip + s * (rise + t), cx, tip + s * t })
    G.poly(col, { cx, tip, cx + half_w, tip + s * rise, cx + half_w, tip + s * (rise + t), cx, tip + s * t })
end

local function esp_pitch_chevrons()
    if pitch_vis <= 0 then return end
    local up = pitch_dir > 0
    local fill = esp_col("F2D81E", pitch_vis)
    local edge = esp_col("000000", pitch_vis * 0.55)
    for _, dy in ipairs(up and PCH_TIPS_UP or PCH_TIPS_DOWN) do
        local tip = CY + dy
        -- a thin dark edge so they read on the sky / ground colours
        chevron(CX, tip + (up and 1.5 or -1.5), up, PCH_HALF_W + 1.5, PCH_RISE, PCH_T + 3, edge)
        chevron(CX, tip, up, PCH_HALF_W, PCH_RISE, PCH_T, fill)
    end
end


-- Altitude and vertical speed units (configuration mode Units page,
-- Installation Manual 6.3.6: alt_unit 0 feet / 1 meters, vs_unit 0 ft/min /
-- 1 m/s). The sim's values, the bugs and every threshold stay in feet and
-- ft/min (altitude alerting 1000 / 200 ft, Pilot's Guide 2.1.3.2, is the
-- same distance in meters); only what is shown is converted. No manual
-- shows a metric screen: tape, labels and steps in meters are our choice.
local M_PER_FT, MPS_PER_FPM = 0.3048, 0.00508
function P.alt_metric() return cfg.alt_unit == 1 end
function P.alt_value(ft) return (cfg.alt_unit == 1) and ft * M_PER_FT or ft end

-- one annunciation word. style: "active" (green), "armed" (white),
-- "reverse" (green box, dark text: automatic transition), "caution" (yellow
-- text: mode lost), "box" (fg on a bg box: AFCS / AP / PFT / PTRIM)
-- a word sprite centred on (x, 233.5) with its corner snapped to whole
-- pixels: centred on a half pixel (AP at x 118.5, all 10 px tall words at
-- y 233.5) X-Plane filters it across two pixels and it looks squashed
-- (user report: AP flat next to PIT)
local function bar_pic(key, x, tint)
    local s = G.size[key]
    if s == nil then return false end
    local x0 = math.floor(x - s[1] / 2 + 0.5)
    local y0 = math.floor(233.5 - s[2] / 2 + 0.5)
    return G.image(key, x0, y0, x0 + s[1], y0 + s[2], tint)
end

local function afcs_word(w, x, style, fg, bg)
    local c = afcs_colors()
    local half = #w * 3.6 + 3
    if style == "active" then
        -- no green art for VNAV: the white word's art tinted in the active green
        -- (the AP/*_G files are the white art recoloured to C.green)
        if not (ART_G[w] and bar_pic(ART_G[w], x))
            and not (ART_W[w] and bar_pic(ART_W[w], x, c.green)) then
            ap_text(w, x, c.green)
        end
    elseif style == "armed" then
        -- fg = optional alpha 0..1 (ALTS fades in, see alts_alpha)
        local a = fg or 1
        if a <= 0 then return end
        if not (ART_W[w] and bar_pic(ART_W[w], x, a < 1 and G.white_alpha(a) or nil)) then
            ap_text(w, x, a < 1 and G.white_alpha(a) or c.white)
        end
    elseif style == "reverse" then
        G.rect(x - half, 227, x + half, 240, c.green)
        ap_text(w, x, c.dark)
    elseif style == "caution" then
        ap_text(w, x, c.yellow)
    elseif style == "box" then
        G.rect(x - half, 227, x + half, 240, bg)
        ap_text(w, x, fg)
    end
end

-- transition / reversion flashes and the disconnect alerts (Pilot's Guide
-- 3.3.2.2, 3.3.3.2): timers on the unit's clock (simulator time)
local fl = { lat = nil, lat_armed = nil, vert = nil, vert_armed = nil, ap = false, yd = false,
    lat_until = 0, lat_style = nil, vert_until = 0, vert_style = nil,
    disc_start = 0, disc_until = 0, disc_abnormal = false, yd_start = 0, yd_until = 0, cut = false }

-- Normal AP / YD disconnect, measured on a G5 8.60 with a GFC 500 (video
-- at 30 fps): 3 cycles of 1 s, each
-- 2/3 s black word on a yellow box, then 1/3 s yellow word without the box;
-- it starts on the box. The abnormal (red) AP alert keeps 10 s.
local DISC_NORMAL_S, DISC_ABNORMAL_S, DISC_CYCLE_S, DISC_BOX_FRAC = 3, 10, 1, 2 / 3
local NAV_LAT = { GPS = true, VOR = true, LOC = true, BC = true }
local NAV_VERT = { GS = true, GP = true, VNAV = true }

local function track_flashes(m, D, st)
    local now = st.clock or 0
    -- the unit was not on the PFD page (other page, off, configuration
    -- mode) or the clock restarted (new flight): start from the current
    -- modes, no alerts. (Not time based: a long frame, e.g. a screenshot,
    -- must not cancel a running alert.)
    if fl.seen == nil or now < fl.seen or fl.reseed then
        fl.reseed = false
        fl.lat, fl.vert, fl.ap, fl.yd = nil, nil, m.ap, m.yd
        fl.lat_until, fl.vert_until, fl.disc_until, fl.yd_until = 0, 0, 0, 0
    end
    fl.seen = now
    if fl.lat ~= nil and m.lat ~= fl.lat then
        if fl.lat_lost and not m.lat_lost then
            -- the data is back: X-Plane's mode is shown again, not a new mode
            fl.lat_until = 0
        elseif m.lat == fl.lat_armed then
            fl.lat_until, fl.lat_style = now + 10, "reverse"
        elseif m.lat == "ROL" and ((NAV_LAT[fl.lat] and D.hsi_show_h == 0) or m.lat_lost) then
            -- the mode's data is gone (X-Plane dropped the nav mode, or the G5's
            -- own heading / GPS / air data / navigation data: apply_data_loss)
            fl.lat_until, fl.lat_style = now + 10, "caution"
        else
            fl.lat_until = 0
        end
    end
    if fl.vert ~= nil and m.vert ~= fl.vert then
        local was = function(w) return fl.vert_armed == w or fl.vert_armed2 == w end
        -- ALT entered any way (capture, the ALT key, Higher / Lower Alt) starts
        -- with the green box (real unit)
        if fl.vert_lost and not m.vert_lost then
            -- the data is back: X-Plane's mode is shown again, not a new mode (no ALT box)
            fl.vert_until = 0
        elseif m.vert == fl.vert_armed or was(m.vert) or m.vert == "ALT" then
            fl.vert_until, fl.vert_style = now + 10, "reverse"
        elseif m.vert == "PIT" and ((NAV_VERT[fl.vert] and D.hsi_show_v == 0) or m.vert_lost) then
            fl.vert_until, fl.vert_style = now + 10, "caution"
        else
            fl.vert_until = 0
        end
    end
    if fl.ap and not m.ap then
        -- autopilot off: normal (pilot) or abnormal (failure / no power /
        -- the G5's own attitude or air data invalid: m.ap_cut, PG 3.3.2.2)
        fl.disc_abnormal = D.otto_fail_warn ~= 0 or D.otto_failed or D.servos_failed or D.ap_has_power == 0
            or m.ap_cut == true
        fl.disc_start = now
        fl.disc_until = now + (fl.disc_abnormal and DISC_ABNORMAL_S or DISC_NORMAL_S)
    elseif m.ap then
        fl.disc_until = 0
    end
    -- yaw damper off: the same yellow alert in the YD field; YD back on ends it
    if fl.yd and not m.yd then
        fl.yd_start, fl.yd_until = now, now + DISC_NORMAL_S
    elseif m.yd then
        fl.yd_until = 0
    end
    fl.lat, fl.lat_armed, fl.vert, fl.vert_armed, fl.ap, fl.yd = m.lat, m.lat_armed, m.vert, m.vert_armed, m.ap, m.yd
    fl.vert_armed2 = m.vert_armed2
    fl.lat_lost, fl.vert_lost = m.lat_lost == true, m.vert_lost == true
    fl.cut = m.ap_cut == true       -- AP cut by the G5's own invalid sensors (the cue turns hollow)
end

P.fl = fl   -- flash state (test-only)

-- autopilot disconnect alert: 0 none, 1 normal (yellow), 2 abnormal (red)
function P.disc_alert(st)
    if (st.clock or 0) >= fl.disc_until then return 0 end
    return fl.disc_abnormal and 2 or 1
end

-- A newly armed ALTS shows after ALTS_DELAY_S and fades in over ALTS_FADE_S
-- (real unit: FD on, AP off from LVL: "ALTS" comes up ~0.3..0.5 s after
-- the active modes, fading in)
local ALTS_DELAY_S, ALTS_FADE_S = 0.5, 0.2
local alts_since = nil

local function alts_alpha(st)
    if alts_since == nil then return 1 end
    local age = (st.clock or 0) - alts_since
    return U.clamp((age - ALTS_DELAY_S) / ALTS_FADE_S, 0, 1)
end

function P.track_afcs(D, st)
    local m = P.afcs_modes(D, st)
    track_flashes(m, D, st)
    if m.vert_armed == "ALTS" or m.vert_armed2 == "ALTS" then
        alts_since = alts_since or (st.clock or 0)
    else
        alts_since = nil
    end
end

local function flashing(until_t, st)
    local now = st.clock or 0
    return now < until_t, U.blink(now, 1)
end

-- normal disconnect alert: running?, box phase? (from the alert's start)
local function disc_phase(start, until_t, st)
    local now = st.clock or 0
    if now >= until_t then return false, false end
    return true, ((now - start) % DISC_CYCLE_S) < DISC_CYCLE_S * DISC_BOX_FRAC
end

local function ap_bar(D, st, gfc, show_modes, m)
    -- 320 px art on x 0..320 (at 159.5 a half column of sky showed on the right)
    G.pic("AP/AP_Bar", 160, 233.5)
    local c = afcs_colors()

    if show_modes then
        if m.lat_armed then afcs_word(m.lat_armed, X_LAT_ARMED, "armed") end
        local on, phase = flashing(fl.lat_until, st)
        if on and fl.lat_style == "reverse" then
            afcs_word(m.lat, X_LAT, phase and "reverse" or "active")
        elseif on and fl.lat_style == "caution" then
            if phase then afcs_word(m.lat, X_LAT, "caution") end
        else
            afcs_word(m.lat, X_LAT, "active")
        end
        on, phase = flashing(fl.vert_until, st)
        if on and fl.vert_style == "reverse" then
            afcs_word(m.vert, X_VERT, phase and "reverse" or "active")
        elseif on and fl.vert_style == "caution" then
            if phase then afcs_word(m.vert, X_VERT, "caution") end
        else
            afcs_word(m.vert, X_VERT, "active")
        end
        if m.ref then
            local fs = G.rfont("bold", 10)
            G.rstr_c(fs, m.ref, X_REF, 228.5, c.green)
            if m.ref_unit == "alt" then
                P.alt_unit(X_REF + #m.ref * 3.8 + 4, 228.5, c.green, 4)
            elseif m.ref_unit then
                stacked(m.ref_unit[1], m.ref_unit[2], X_REF + #m.ref * 3.8 + 4, 228.5, c.green, 4)
            end
        end
        -- the armed word takes the reference's place when there is none
        -- ("PIT ALTS", figure 3-9) and the far field otherwise ("VS +500 ALTS")
        if m.vert_armed then
            if m.ref then
                afcs_word(m.vert_armed, X_ARMED, "armed", m.vert_armed == "ALTS" and alts_alpha(st) or nil)
            else
                afcs_word(m.vert_armed, X_REF, "armed", m.vert_armed == "ALTS" and alts_alpha(st) or nil)
                if m.vert_armed2 then
                    afcs_word(m.vert_armed2, X_ARMED, "armed", m.vert_armed2 == "ALTS" and alts_alpha(st) or nil)
                end
            end
        end
    end

    -- AP field (Pilot's Guide table 3-12): failures, preflight test, disconnect, engaged
    local up = st.up_t or 99
    -- preflight test: the provider's ap_pft (0 none, 1 running, 2 failed), the
    -- same on every unit; without it this unit times it from its own boot
    local pft = P.Esp and P.Esp.pic.pft
    if D.otto_failed then
        afcs_word("AFCS", X_AP, "box", c.white, c.red)
    elseif D.servos_failed or D.ap_has_power == 0 or pft == 2 then
        -- AP not available (servos failed, no autopilot power, preflight test
        -- failed): yellow + red X
        afcs_word("AP", X_AP, "caution")
        G.line(X_AP - 9, 228, X_AP + 9, 239, c.red, 2)
        G.line(X_AP - 9, 239, X_AP + 9, 228, c.red, 2)
    elseif pft == 1 or (pft == nil and gfc and up < cfg.afcs_pft_s) then
        afcs_word("PFT", X_AP, "box", c.black, c.white)
    elseif fl.disc_abnormal then
        local on, phase = flashing(fl.disc_until, st)
        if on then
            if phase then afcs_word("AP", X_AP, "box", c.red, c.black) end
        elseif m.ap then
            afcs_word("AP", X_AP, "active")
        end
    else
        local on, box = disc_phase(fl.disc_start, fl.disc_until, st)
        if on then
            afcs_word("AP", X_AP, box and "box" or "caution", c.black, c.yellow)
        elseif m.ap then
            afcs_word("AP", X_AP, "active")
        end
    end
    if D.trim_fail ~= 0 then
        -- beside the red AFCS box (right edge 136), not over it
        afcs_word("PTRIM", X_YD + (D.otto_failed and 13 or 9), "box", c.white, c.red)
    elseif D.otto_failed then
        -- the red AFCS flag says the autopilot has failed (Pilot's Guide table 3-11:
        -- autopilot and trim inoperative): no YD field next to it
    elseif D.servos_failed or D.ap_has_power == 0 or D.yd_failed then
        -- YD not available (servos failed / no AP power): yellow + red X
        afcs_word("YD", X_YD, "caution")
        G.line(X_YD - 9, 228, X_YD + 9, 239, c.red, 2)
        G.line(X_YD - 9, 239, X_YD + 9, 228, c.red, 2)
    else
        local on, box = disc_phase(fl.yd_start, fl.yd_until, st)
        if on then
            afcs_word("YD", X_YD, box and "box" or "caution", c.black, c.yellow)
        elseif m.yd then
            afcs_word("YD", X_YD, "active")
        end
    end
end

-- TRIM UP / TRIM DOWN (Pilot's Guide 3.4.1, figures 3-21 / 3-22): black on
-- yellow, centred below the aircraft symbol.
-- X-Plane's autopilot_trim_up / _down annunciators chatter in level flight
-- (both within a second; user report), so each direction is
-- integrated every frame (P.update, simulator time): +dt while it is lit,
-- -dt while not, kept in 0..TRIM_MAX_S. Shown from TRIM_ON_S, hidden again
-- below TRIM_OFF_S; a direction lit only part of the time never builds up.
local TRIM_ON_S, TRIM_OFF_S, TRIM_MAX_S = 2.0, 0.5, 3.0
function P.trim_update(D, st, dt)
    local t = st.trim
    if t == nil or st.mode < Sys.PFD then
        t = { up = 0, dn = 0, shown = nil }
        st.trim = t
    end
    dt = U.clamp(dt or 0, 0, 0.5)
    t.up = U.clamp(t.up + ((D.trim_up ~= 0) and dt or -dt), 0, TRIM_MAX_S)
    t.dn = U.clamp(t.dn + ((D.trim_down ~= 0) and dt or -dt), 0, TRIM_MAX_S)
    if t.shown == "up" and t.up < TRIM_OFF_S then t.shown = nil end
    if t.shown == "dn" and t.dn < TRIM_OFF_S then t.shown = nil end
    if t.shown == nil then
        if t.up >= TRIM_ON_S and t.up >= t.dn then t.shown = "up"
        elseif t.dn >= TRIM_ON_S then t.shown = "dn" end
    end
end

local function trim_alert(D, st)
    local shown = st.trim and st.trim.shown
    if shown == nil then return end
    local c = afcs_colors()
    G.rect(109, 62, 209, 79, c.yellow)
    G.rstr_c(G.rfont("bold", 10), (shown == "up") and "TRIM UP" or "TRIM DOWN", 159, 65.5, c.black)
end


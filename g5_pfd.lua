-- Metric VSI (vs_unit = 1). The VS_*config scales have their fpm labels
-- baked in, so this scale is drawn in their style: grey ticks at the right
-- edge (labelled 7 x 2 px, the others 4 x 1 px every 1 m/s), labels in the
-- 6 px raster font left of them, nothing at zero. vsi_scale 15 -> +/-8 m/s
-- (labels 4 6 8, 1575 fpm), 30 -> +/-15 m/s (5 10 15, 2953 fpm). The tick at
-- +/-2 m/s stays but carries no label: it would sit half under the altitude
-- readout box (checked 2026-11-12; the 5 m/s labels of scale 30 are clear).
-- Our choice: no manual shows a metric VSI.
local VSI_METRIC = { [15] = { 8, 2 }, [30] = { 15, 5 } }
local FPM_PER_MPS = 1 / 0.00508
local vsi_tick_col
local VSI_LABEL_CLEAR = 30   -- px from the zero line: the altitude box (+-27) hides a label nearer than this
local function vsi_scale_metric(range_ms, step)
    vsi_tick_col = vsi_tick_col or G.hex("BFBFBF")
    local fs = G.rfont("bold", 6)
    for v = -range_ms, range_ms do
        local y = U.round(120.5 + v / range_ms * 107.5) + 0.5
        if v % step == 0 then
            G.rect(313.5, y - 1, 320, y + 1, vsi_tick_col)
            if v ~= 0 and math.abs(y - 120.5) >= VSI_LABEL_CLEAR then
                G.rstr(fs, tostring(math.abs(v)), 310.5, y - 3, vsi_tick_col, G.JR)
            end
        else
            G.rect(316.5, y - 0.5, 320, y + 0.5, vsi_tick_col)
        end
    end
end

local function vsi(D, st)
    -- only 15 / 30 have art and metric labels; anything else is 15
    local scale = (cfg.vsi_scale == 30) and 30 or 15
    local dir = (scale == 15) and "VS_15config/" or "VS_30config/"
    local range = scale * 100
    if cfg.vs_unit == 1 then
        local m = VSI_METRIC[scale]
        range = m[1] * FPM_PER_MPS
        vsi_scale_metric(m[1], m[2])
    else
        G.pic(dir .. "VS_Stripe_Full", 311, 121)
    end
    local k = 107 / range
    local vy = U.clamp(D.vs, -range, range) * k
    if math.abs(vy) > 0.5 then
        -- flush with the screen's right edge (x 320); at 319.5 a half column
        -- of sky showed beside it in the sim

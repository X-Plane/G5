-- Data the G5 itself has lost (Pilot's Guide 3.3.2.2, 3.3.3.2, 3.3.4.6.1,
-- 3.3.5.4, 3.3.5.8): X-Plane's autopilot never reacts to what the G5's own
-- sensors report, so the G5 applies the rules to what it shows.
--   * "If the information required to compute a flight director mode becomes
--     invalid or unavailable, the flight director automatically reverts to
--     the default mode for that axis" (ROL / PIT), flashing yellow for 10 s
--     (track_flashes). The text names no sensors, so each mode gets the G5
--     data it cannot work without (our reading):
--       HDG   magnetic heading (a magnetometer is installed and its heading
--             is lost; a unit without one never had HDG)
--       TRK   GPS ground track          GPS  GPS reception, navigation data
--       VOR / LOC / BC / GS   navigation data (the selected source stopped
--             sending, g5_fail nav_lost)   GP  GPS reception or navigation data
--       ALT / VS / IAS / FPA   air data (altitude, vertical speed, airspeed;
--             FPA from the vertical speed). PIT, ROL, TO, GA, LVL need only the
--             attitude: without it the flight director is gone altogether
--     VNAV (deviation invalid) and the nav / GS signal losses X-Plane itself
--     shows (hsi_display_*) are handled in track_flashes as before.
--   * "Automatic disengagement ... due to ... invalid sensor data" is a flashing
--     red AP: the autopilot cannot run without the attitude or the air data.
--     Heading is not on this list: its loss only reverts HDG to ROL (above).
-- The modes below are the shown ones; the X-Plane ones stay untouched in
-- P.afcs_modes(D) (no st): the heading sync reads those.
local AIR_VERT = { ALT = true, VS = true, IAS = true, FPA = true, ALTS = true }

-- ALTS capture (Pilot's Guide 3.3.4.2 / 3.3.4.3): nearing the selected
-- altitude the flight director goes into ALTS capture with ALT armed (green
-- ALTS, white ALT), and 50 ft from it into ALT hold. X-Plane has no capture
-- state of its own: it goes from VS / PIT / IAS straight to altitude hold.
-- Our rule, per unit (P.cap, updated every frame on any page by P.update):
--   * enter only on the frame X-Plane goes into altitude hold
--     (altitude_hold_status 2 or altitude_mode 6), with ALTS armed the frame
--     before, on the preselected altitude (alt_hold_is_alt_sel_any = 1;
--     without that dataref: held altitude within CAP.DIAL_TOL_FT of X-Plane's
--     selected altitude) and more than CAP.WINDOW_FT away from it;
--   * stay while X-Plane holds, more than CAP.WINDOW_FT from the target, the
--     held altitude not moved by more than CAP.TARGET_TOL_FT, FD or AP on,
--     not LVL, air data valid, the unit on the PFD / HSI page;
--   * anything else ends it, and only a new entry into altitude hold starts
--     it again (drifting more than 50 ft off later is plain ALT).
-- If X-Plane only goes into altitude hold within 50 ft of the target, there
-- is no capture phase to show: ALT at once.
-- Heights in ft whatever the display unit.
local CAP = {
    -- Pilot's Guide: ALT hold 50 ft from the selected altitude. Whether a
    -- capture phase shows at all depends on X-Plane going into altitude hold
    -- further out (measured in X-Plane 12.4.4: it switches 75 ft from the
    -- target in a VS climb or descent, 84 ft in an IAS descent)
    WINDOW_FT = 50,
    -- our rule: held altitude = selected altitude when sel_any is missing
    -- (measured in X-Plane 12.4.4: the held altitude equals the dial exactly)
    DIAL_TOL_FT = 2,
    -- our rule: the held altitude moved = the target changed (measured in
    -- X-Plane 12.4.4: it stays put during the capture)
    TARGET_TOL_FT = 1,
}
P.cap = { on = false, target = 0, prev_alt_on = false, prev_armed = false }

function P.cap_update(D, st)
    -- (runs from Pfd.update, outside a unit's view_begin: D.alt is X-Plane's
    -- own pilot altitude, the one its altitude hold works on)
    local cap = P.cap
    if st.mode ~= Sys.PFD and st.mode ~= Sys.HSI then
        -- off, booting, configuration mode: start over (coming back in the
        -- middle of a capture shows ALT)
        cap.on, cap.prev_alt_on, cap.prev_armed = false, false, false
        return
    end
    local alt_on = D.alt_hold_status == 2 or D.alt_mode == 6
    -- altitude_hold_armed alone: alts_armed is 1 almost always in X-Plane 12.4
    -- (also in PIT), altitude_hold_armed is 1 in VS / IAS and 0 in PIT
    local armed = D.alt_hold_armed ~= 0 or D.alt_hold_status == 1
    local presel
    if D.alt_sel_any ~= nil then
        presel = D.alt_sel_any == 1
    else
        presel = math.abs(D.alt_hold - (D.alt_dial_xp or D.alt_bug)) <= CAP.DIAL_TOL_FT
    end
    if alt_on and not cap.prev_alt_on and cap.prev_armed and presel
        and math.abs(D.alt - D.alt_hold) > CAP.WINDOW_FT then
        cap.on, cap.target = true, D.alt_hold
    end
    if cap.on and not (alt_on and math.abs(D.alt - cap.target) > CAP.WINDOW_FT
        and math.abs(D.alt_hold - cap.target) <= CAP.TARGET_TOL_FT
        and D.ap_mode >= 1 and not D.lvl and st.valid.air) then
        cap.on = false
    end
    cap.prev_alt_on, cap.prev_armed = alt_on, armed
end

local function lat_data_lost(lat, st)
    local v = st.valid
    if lat == "HDG" then return v.hdg_flag == true
    elseif lat == "TRK" then return not v.gps
    elseif lat == "GPS" then return not v.gps or st.nav_lost == true
    elseif lat == "VOR" or lat == "LOC" or lat == "BC" then return st.nav_lost == true end
    return false
end

local function vert_data_lost(vert, st)
    local v = st.valid
    if AIR_VERT[vert] then return not v.air
    elseif vert == "GS" then return st.nav_lost == true
    elseif vert == "GP" then return not v.gps or st.nav_lost == true end
    return false
end

-- m (from P.afcs_modes) -> what the G5 shows: lost modes revert (m.lat_lost /
-- m.vert_lost tell track_flashes why), an autopilot cut by invalid sensors
-- is not engaged any more (m.ap_cut: the red alert, abnormal in track_flashes)
local function apply_data_loss(m, st)
    local v = st.valid
    if m.ap and (not v.att or not v.air) then
        m.ap, m.ap_cut = false, true
    end
    if lat_data_lost(m.lat, st) then
        m.lat, m.lat_lost = "ROL", true
    end
    if vert_data_lost(m.vert, st) then
        m.vert, m.vert_lost = "PIT", true
        m.ref, m.ref_unit = nil, nil
    end
end

-- Mode decoding (pure: D -> modes), from X-Plane's per-mode status datarefs
-- (0 off / 1 armed / 2 active) with the mode enums as a fallback. Words as
-- annunciated by the G5 (Pilot's Guide tables 3-4 .. 3-9). With the unit's
-- state st the modes are the shown ones (data the G5 has lost: apply_data_loss).
function P.afcs_modes(D, st)
    local m = {}
    local gps = D.hsi_src == 2
    local t = nav_type(D)
    local loc = loc_tuned(D)
    local function navword() return gps and "GPS" or (loc and "LOC" or "VOR") end
    local ground = (D.on_ground or 0) ~= 0

    -- lateral. A VOR / LOC is only captured with a valid deviation: X-Plane's
    -- S-TEC reports NAV captured at once even with "NO LOC"; the GFC 500
    -- shows it armed (white) over ROL until the needle is alive (real-unit
    -- video).
    local nav_on = D.nav_status == 2 or D.apr_status == 2
    local nav_live = gps or D.hsi_show_h ~= 0
    if D.toga_lat_status == 2 or D.hdg_mode == 10 then m.lat = ground and "TO" or "GA"
    elseif D.bc_status == 2 then m.lat = "BC"
    elseif D.gpss_status == 2 or D.hdg_mode == 13 then m.lat = "GPS"
    elseif nav_on and nav_live then m.lat = navword()
    elseif D.track_status == 2 or D.hdg_mode == 18 then m.lat = "TRK"
    elseif D.hdg_status == 2 or D.hdg_hold_status == 2 or D.hdg_mode == 1 or D.hdg_mode == 14 then m.lat = "HDG"
    else m.lat = "ROL" end
    if D.bc_status == 1 then m.lat_armed = "BC"
    elseif D.gpss_status == 1 then m.lat_armed = "GPS"
    elseif D.nav_status == 1 or D.apr_status == 1 or (nav_on and not nav_live) then m.lat_armed = navword() end
    if m.lat_armed == m.lat then m.lat_armed = nil end

    -- vertical, with its reference
    if D.toga_status == 2 or D.alt_mode == 10 then m.vert = ground and "TO" or "GA"
    elseif (D.gs_status == 2 or D.alt_mode == 8) and D.hsi_show_v ~= 0 then m.vert = gps and "GP" or "GS"
    elseif D.vnav_status == 2 or D.alt_mode == 9 then m.vert = "VNAV"   -- PG 3.3.4: "VNAV" (was "VNV" until 2026-11-12)
    elseif D.alt_hold_status == 2 or D.alt_mode == 6 then
        m.vert = "ALT"
        -- the held altitude, not the bug (ft to the 10, m to the 1)
        m.ref = P.alt_metric() and tostring(U.round(P.alt_value(D.alt_hold)))
            or tostring(U.round(D.alt_hold / 10) * 10)
        m.ref_unit = "alt"
    elseif D.vvi_status == 2 or D.alt_mode == 4 then
        m.vert = "VS"
        m.ref = P.vs_text(D.vs_bug)
    elseif D.speed_status == 2 or D.alt_mode == 5 then
        m.vert = "IAS"
        m.ref = tostring(U.round(speed_value(D.spd_bug)))
        -- stacked unit like "ft" (real unit: "IAS 61kt")
        m.ref_unit = ({ [0] = { "k", "t" }, [1] = { "m", "h" }, [2] = { "k", "h" } })[cfg.speed_unit] or { "k", "t" }
    elseif D.fpa_status == 2 or D.alt_mode == 19 then
        m.vert = "FPA"
        m.ref = string.format("%+.1f", D.fpa)
    else m.vert = "PIT" end
    -- armed vertical words, up to two (real unit after APPR: "PIT GS ALTS"):
    -- the approach glideslope / glidepath, then one of ALTV / VNAV / ALTS.
    -- GS arms with an approach on a VOR / LOC source (X-Plane's S-TEC only
    -- reports approach_status), or from X-Plane's glideslope_status 1.
    local gs_active = m.vert == "GS" or m.vert == "GP"
    local gs_armed = not gs_active and (D.gs_status == 1 or D.gs_armed ~= 0
        or (D.apr_status ~= 0 and (gps or loc)) or ((D.gs_status == 2 or D.alt_mode == 8) and D.hsi_show_v == 0))
    -- GP (GPS source) only with evidence that the approach has a glidepath
    -- (Pilot's Guide 3.3.4.7: LPV, LP+V, LNAV/VNAV, LNAV+V; an LNAV approach
    -- has none). Our rule, positive evidence only: X-Plane's own GPS arms the
    -- glideslope on any APPR, so glideslope_status 1 alone is no evidence.
    -- Evidence: gps_has_glideslope, a vertical deviation shown, or a CDI phase
    -- with vertical guidance (8 LNAV+V, 9 L/VNAV, 11 LPV, 12 LP+V); none
    -- while NO GP is up. VOR / LOC (GS) unchanged.
    if gs_armed and gps then
        local c = D.gps_cdi
        gs_armed = (D.gps_has_gs ~= 0 or D.hsi_show_v ~= 0 or c == 8 or c == 9 or c == 11 or c == 12)
            and not D.no_gp
    end
    local va = {}
    if gs_armed then va[#va + 1] = gps and "GP" or "GS" end
    if D.altv_armed ~= 0 then va[#va + 1] = "ALTV"       -- VNAV target altitude (figure 3-14)
    elseif D.vnav_status == 1 then
        -- the active word is "VNAV" too now: never the same word twice
        if m.vert ~= "VNAV" then va[#va + 1] = "VNAV" end
    elseif (D.alt_armed ~= 0 or D.alt_hold_status == 1) and m.vert ~= "ALT" then
        -- no ALTS while holding an altitude: nothing to capture (real unit,
        -- FD + ALT = "ROL | ALT 660ft"); X-Plane keeps alts_armed set
        va[#va + 1] = "ALTS"
    end
    -- ALTS capture (P.cap, our rule above): shown as green ALTS with ALT
    -- armed, no reference ("ALTS ALT", "ALTS GP ALT" like "PIT GS ALTS").
    -- Only with the unit's state: P.afcs_modes(D) keeps X-Plane's ALT
    if st ~= nil and P.cap.on and m.vert == "ALT" then
        m.vert, m.ref, m.ref_unit = "ALTS", nil, nil
        for i = #va, 1, -1 do va[i] = nil end
        if gs_armed then va[1] = gps and "GP" or "GS" end
        va[#va + 1] = "ALT"
    end
    m.vert_armed, m.vert_armed2 = va[1], va[2]
    -- Level mode (g5_sim Sim.update_lvl): "LVL" in both fields, nothing armed
    -- (real unit: AP + FD + LVL = "LVL | AP | LVL")
    if D.lvl then
        m.lat, m.vert = "LVL", "LVL"
        m.lat_armed, m.vert_armed, m.vert_armed2, m.ref, m.ref_unit = nil, nil, nil, nil, nil
    end
    -- TO / GA are coupled pitch and roll modes: both fields
    if m.vert == "TO" or m.vert == "GA" then m.lat = m.vert end
    if m.lat == "TO" or m.lat == "GA" then m.vert = m.lat end
    m.ap = D.servos_on ~= 0
    m.yd = D.yd_on ~= 0
    if st ~= nil and st.valid ~= nil then apply_data_loss(m, st) end
    return m
end


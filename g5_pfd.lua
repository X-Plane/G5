        local v = U.round(fpm * MPS_PER_FPM * 10) / 10
        if v == 0 then v = 0 end       -- no "-0.0"
        return string.format("%+.1f", v)
    end
    local v = U.round(fpm / 10) * 10
    return ((v < 0) and "-" or "+") .. tostring(math.abs(v))
end

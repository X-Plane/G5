        clip(x0, y0, x0 + 1, y1) G.pic("Vert_GS_Box", x, VDI_Y) G.unclip()
        clip(x1 - 1, y0, x1, y1) G.pic("Vert_GS_Box", x, VDI_Y) G.unclip()
        G.rect(x0 + 1, y0, x1 - 1, y1, G.black_alpha(0.65))
        G.textc("N", x, VDI_C + 15, 9, C.white, G.JC, G.font)

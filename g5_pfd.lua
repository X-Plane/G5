local turn_rate = 0
local last_hdg = nil

-- Roll scale levels (from real-unit photos). The elements
-- stacked at the top of the screen, the AFCS bar (BAR_H) and below it the
-- heading tape (HDG_H, hidden while ALIGNING), each take ARC_STEP px off the
-- arc radius; the zero mark always sits against the lowest one, and the
-- attitude centre (with the tapes and readouts) takes up the rest of its
-- height. Pilot's Guide screenshots, bar on / off with the heading tape: R
-- 84.9 -> 78.2, attitude 7 px down, heading tape 14 px down. The artwork is
-- the one-element layout (heading tape, no bar). Animated in whole pixels
-- (one arc cell per pixel): the bar slides in from above with the top row,
-- eased over BAR_S, the heading tape as heading_tape slides it in; at once
-- when the PFD comes up or the sim is paused.
local ARC_STEP, BAR_H, HDG_H, HDG_SLIDE = 7, 14, 24, 26
local BAR_S = 0.25
local bar_v, bar_target, bar_snap, bar_gfc = 0, 0, true, false

function P.speed_alive() return spd_alive end

-- The unit's view of the navigation data (G5.lua draw_screen): no CDI / VDI
-- (and so no NO GP, g5_sim Sim.update_no_gp) with Navigation Data disabled,
-- nor with a GPS source while GPS navigation is lost. One rule for the draw
-- (G5.lua) and the mode flashes (P.update), so the two cannot drift apart.
-- P.mask_nav returns what P.unmask_nav puts back (no table: called every
-- frame).
function P.nav_masked(D, st)
    return cfg.nav_data == 0 or (D.hsi_src == 2 and st.gps_nav_lost)
end

function P.mask_nav(D, st)
    local sh, sv, ng = D.hsi_show_h, D.hsi_show_v, D.no_gp
    if P.nav_masked(D, st) then
        D.hsi_show_h, D.hsi_show_v, D.no_gp = 0, 0, false
    end
    return sh, sv, ng
end

function P.unmask_nav(D, sh, sv, ng)
    D.hsi_show_h, D.hsi_show_v, D.no_gp = sh, sv, ng
end

function P.update(dt, D)
    update_speed_alive(D)
    local st = Sys.st
    esp_anim(dt, D, st)
    P.trim_update(D, st, dt)
    -- every frame on any page: a capture that starts on the HSI page shows
    -- on the PFD page too
    P.cap_update(D, st)
    if st.aligning or st.mode < Sys.PFD then
        hdg_vis = 0
    else
        hdg_vis = U.approach(hdg_vis, 1, 1 / HDG_IN_S, dt)
    end
    if st.mode == Sys.PFD then
        -- the draw sees the nav data masked (P.mask_nav, G5.lua); track the
        -- mode flashes on that same view
        local sh, sv, ng = P.mask_nav(D, st)
        local ok, err = pcall(P.track_afcs, D, st)
        P.unmask_nav(D, sh, sv, ng)
        if not ok then error(err, 0) end
        bar_target = P.bar_wanted(D, st, bar_gfc) and 1 or 0
        if dt > 0 then
            bar_v = U.approach(bar_v, bar_target, 1 / BAR_S, dt)
        else
            bar_snap = true
        end
    else
        P.fl.reseed = true
        bar_snap = true
    end
    -- turn rate from the AHRS heading (deg/s), lightly smoothed
    if last_hdg ~= nil and dt > 0 then
        local r = U.angdiff(D.hdg, last_hdg) / dt
        -- a new flight / position jump is not a turn
        if math.abs(r) > 100 then r = 0 end
        turn_rate = turn_rate + (r - turn_rate) * math.min(1, dt * 4)
    end
    last_hdg = D.hdg
end

